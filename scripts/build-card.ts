/**
 * Bundles card/main.ts, the shared renderer and the shared CSS into ONE html string.
 * The MCP Apps host serves it in a sandboxed iframe with no network, so nothing may be external.
 */
import { build } from "esbuild";
import { writeFileSync } from "node:fs";

const out = await build({
  entryPoints: ["card/main.ts"],
  bundle: true,
  minify: true,
  write: false,
  format: "iife",
  target: "es2022",
  platform: "browser",
  loader: { ".css": "text" },
  legalComments: "none",
});

const js = out.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
const html = `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Pathfinder</title></head><body><div id="root"></div><script>${js}</script></body></html>`;
writeFileSync("lib/card-html.generated.ts", `// generated by scripts/build-card.ts. Do not edit.\nexport const CARD_HTML = ${JSON.stringify(html)};\n`);
console.log(`card: ${(html.length / 1024).toFixed(0)} KB, self-contained`);
